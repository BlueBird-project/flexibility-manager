         xlab="", ylab="Tb [C]", main="Simulated vs. measured Tb",
         ylim=ylim2)
    lines(t.hours[day.idx], Tbot.sim[day.idx], col="darkorange", lwd=1.5, lty=1)
    legend("topright", legend=c("measured", "simulated (fitted, open-loop)"),
           col=c("gray50", "darkorange"), lty=c(1,1), lwd=1.5, bty="n", cex=0.8)

    mtext("Time [h]", side=1, outer=TRUE, line=1)
    par(mfrow=c(1,1))
}
