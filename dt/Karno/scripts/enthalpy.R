# State 
# [TT, Tc] 
# TT = alpha Tt + (1 - alpha) Tb
# Tc = Tb

# Linear SDE 
model$addSystem(
    dTT ~  1/exp(log_Ctank) * (exp(log_COP)*Pel - Qdist)*dt     + exp(log_sigma_TT)*dw,
    dTc ~ (1/exp(log_tau) * (Tr - Tc) + exp(log_lambda)*Pel)*dt + exp(log_sigma_Tc)*dw
)

model$addObs(
   Tt ~ (1 / exp(log_alpha)*TT + (1 - 1/exp(log_alpha))*Tc),
   Tb ~ Tc 
)

model$setVariance(
    Tt ~ sigma_Tt,
    Tb ~ sigma_Tb
)

model$addInput(
    Pel, 
    Qdist, 
    Tr
)

model$setParameter( 
    log_Ctank    = c(initial=log(10460000.0), lower=log(8000000.0), upper=log(12500000.0)), # Tank total capacity
    log_COP      = c(initial=log(4.5) , lower=log(3.0) , upper=log(6.0)),          # Coefficient of Performence 
    log_tau      = c(initial=log(3600), lower=log(1000), upper=log(10800)),        # Tank bottom temperature flush time constant
    log_lambda   = c(initial=log(1e-6), lower=log(1e-8), upper=log(1e-4)),         # Charging mixing gain 
    log_alpha    = c(initial=log(0.5) , lower=-Inf     , upper=0.0),               # Mixing ratio proxy
    # Process noise  
    log_sigma_TT = c(initial=log(0.05), lower=-Inf, upper=log(0.15)),              # Process noise state 1
    log_sigma_Tc = c(initial=log(0.05), lower=-Inf, upper=log(0.15)),              # Process noise state 2
    # Measurement noise
    sigma_Tt = c(initial=0.1, lower=0.01, upper=0.2),                              # Process noise measurement 1
    sigma_Tb = c(initial=0.1, lower=0.01, upper=0.2)                               # Process noise measurement 2
)

